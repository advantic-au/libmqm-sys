use libmqm_sys::str as mqstr;
use std::str;

pub type MqCStrFnExtern = unsafe extern "C" fn(mqstr::MQLONG) -> *mut std::os::raw::c_char;

#[derive(Clone, Copy)]
pub struct ConstantEntry<'a> {
    pub new_type: &'a str,
    pub orig_type: &'a str,
    pub str_fn: MqCStrFnExtern,
    pub prefix: &'a str,
    pub usage: &'a str,
    pub feature: Option<&'a str>,
    pub doc: Option<&'a str>,
}

impl<'a> ConstantEntry<'a> {
    pub const fn new(
        prefix: &'a str,
        new_type: &'a str,
        str_fn: MqCStrFnExtern,
        orig_type: &'a str,
        usage: &'a str,
        feature: Option<&'a str>,
        doc: Option<&'a str>,
    ) -> Self {
        Self {
            new_type,
            orig_type,
            str_fn,
            prefix,
            usage,
            feature,
            doc,
        }
    }
}

const fn c<'a>(
    prefix: &'a str,
    new_type: &'a str,
    str_fn: MqCStrFnExtern,
    orig_type: &'a str,
    usage: &'a str,
    feature: Option<&'a str>,
    doc: Option<&'a str>,
) -> ConstantEntry<'a> {
    ConstantEntry::new(prefix, new_type, str_fn, orig_type, usage, feature, doc)
}

